package extractor

import (
	"context"
	"time"
)

type MediaFormat struct {
	FormatID string `json:"format_id"`
	Ext      string `json:"ext"`
	Quality  string `json:"quality"` // 1080p, 720p, audio_only, etc.
	Width    int    `json:"width"`
	Height   int    `json:"height"`
	FPS      int    `json:"fps"`
	VCodec   string `json:"vcodec"`
	ACodec   string `json:"acodec"`
	Bitrate  int    `json:"bitrate"`   // kbps
	FileSize int64  `json:"file_size"` // bytes, may be 0 if unknown
	Protocol string `json:"protocol"`  // https, m3u8, dash
	URL      string `json:"url"`       // direct download URL
	IsAudio  bool   `json:"is_audio"`
	IsVideo  bool   `json:"is_video"`
	Language string `json:"language"` // for audio/subtitles
}

type MediaInfo struct {
	ID            string                     `json:"id"`
	Title         string                     `json:"title"`
	Description   string                     `json:"description"`
	Duration      int                        `json:"duration"` // seconds
	Thumbnail     string                     `json:"thumbnail"`
	Uploader      string                     `json:"uploader"`
	UploadDate    string                     `json:"upload_date"`
	ViewCount     int64                      `json:"view_count"`
	LikeCount     int64                      `json:"like_count"`
	Tags          []string                   `json:"tags"`
	Formats       []MediaFormat              `json:"formats"`
	Subtitles     map[string][]SubtitleTrack `json:"subtitles"` // lang -> tracks
	Platform      string                     `json:"platform"`
	URL           string                     `json:"url"`
	AgeRestricted bool                       `json:"age_restricted"`
	LiveStatus    string                     `json:"live_status"` // none, live, post_live, upcoming
}

type SubtitleTrack struct {
	URL           string `json:"url"`
	Ext           string `json:"ext"` // vtt, srt, ass
	Language      string `json:"language"`
	LanguageName  string `json:"language_name"`
	AutoGenerated bool   `json:"auto_generated"`
}

type DownloadResult struct {
	FilePath     string      `json:"file_path"`
	Format       MediaFormat `json:"format"`
	Title        string      `json:"title"`
	Thumbnail    string      `json:"thumbnail"`
	Duration     int         `json:"duration"`
	FileSize     int64       `json:"file_size"`
	DownloadedAt time.Time   `json:"downloaded_at"`
}

type ProgressFunc func(downloaded, total int64, speed float64, eta time.Duration)

type Extractor interface {
	// Name возвращает имя платформы (youtube, tiktok, instagram, ...)
	Name() string

	// CanHandle проверяет, может ли экстрактор обработать этот URL
	CanHandle(url string) bool

	// Extract получает метаданные и доступные форматы БЕЗ скачивания
	Extract(ctx context.Context, url string) (*MediaInfo, error)

	// Download скачивает выбранный формат в файл, вызывает progress callback
	Download(ctx context.Context, url string, format MediaFormat, progress ProgressFunc) (*DownloadResult, error)

	// GetBestFormat возвращает лучший формат по конфигу (quality, audio_only, etc.)
	GetBestFormat(info *MediaInfo, qualityPref string, audioOnly bool) (MediaFormat, error)
}

type Downloader interface {
	Download(ctx context.Context, url, dest string, progress ProgressFunc) error
	GetFileSize(url string) (int64, error)
}
