type YouTubeExtractor struct {
	client *youtube.Client
	config YouTubeConfig
}

type YouTubeConfig struct {
	QualityPreference string
	DownloadSubtitles bool
	SubtitleLangs     []string
}

func NewYouTubeExtractor(config YouTubeConfig) *YouTubeExtractor {
	return &YouTubeExtractor{
		client: &youtube.Client{},
		config: config,
	}
}

func (e *YouTubeExtractor) Name() string {
	return "youtube"
}

func (e *YouTubeExtractor) CanHandle(url string) bool {
	return strings.Contains(url, "youtube.com") || strings.Contains(url, "youtu.be")
}

func (e *YouTubeExtractor) Extract(ctx context.Context, url string) (*MediaInfo, error) {
	video, err := e.client.GetVideo(url)
	if err != nil {
		return nil, fmt.Errorf("youtube get video: %w", err)
	}

	info := &MediaInfo{
		ID:            video.ID,
		Title:         video.Title,
		Description:   video.Description,
		Duration:      int(video.Duration.Seconds()),
		Thumbnail:     video.Thumbnails[0].URL,
		Uploader:      video.Author,
		UploadDate:    video.PublishedAt.Format("20060102"),
		ViewCount:     int64(video.ViewCount),
		Platform:      "youtube",
		URL:           url,
		AgeRestricted: video.IsAgeRestricted,
		LiveStatus:    string(video.LiveStatus),
		Formats:       make([]MediaFormat, 0),
		Subtitles:     make(map[string][]SubtitleTrack),
	}

	// Parse formats
	for _, f := range video.Formats {
		format := MediaFormat{
			FormatID: f.Itag,
			Ext:      f.MimeType[strings.Index(f.MimeType, "/")+1:],
			Quality:  f.QualityLabel,
			Width:    f.Width,
			Height:   f.Height,
			FPS:      f.FPS,
			VCodec:   f.VideoCodec,
			ACodec:   f.AudioCodec,
			Bitrate:  int(f.Bitrate / 1000), // to kbps
			FileSize: int64(f.ContentLength),
			Protocol: "https",
			URL:      f.URL,
			IsAudio:  f.AudioQuality != "" && f.VideoCodec == "",
			IsVideo:  f.VideoCodec != "",
		}
		if format.Quality == "" {
			if format.IsAudio {
				format.Quality = "audio_only"
			} else {
				format.Quality = fmt.Sprintf("%dp", format.Height)
			}
		}
		info.Formats = append(info.Formats, format)
	}

	// Parse subtitles
	if e.config.DownloadSubtitles {
		for _, track := range video.Subtitles {
			lang := track.LanguageCode
			if len(e.config.SubtitleLangs) > 0 {
				found := false
				for _, l := range e.config.SubtitleLangs {
					if strings.HasPrefix(lang, l) {
						found = true
						break
					}
				}
				if !found {
					continue
				}
			}
			info.Subtitles[lang] = append(info.Subtitles[lang], SubtitleTrack{
				URL:            track.URL,
				Ext:            "vtt",
				Language:       lang,
				LanguageName:   track.LanguageName,
				AutoGenerated:  track.AutoGenerated,
			})
		}
	}

	logrus.Debugf("YouTube: extracted %d formats, %d subtitle langs for %s", len(info.Formats), len(info.Subtitles), video.ID)
	return info, nil
}

func (e *YouTubeExtractor) GetBestFormat(info *MediaInfo, qualityPref string, audioOnly bool) (MediaFormat, error) {
	if audioOnly {
		return e.getBestAudio(info)
	}

	var candidates []MediaFormat
	for _, f := range info.Formats {
		if f.IsVideo && !f.IsAudio {
			// Prefer progressive (video+audio) or we'll need to merge
			if f.VCodec != "" && f.ACodec != "" {
				candidates = append(candidates, f)
			}
		}
	}

	if len(candidates) == 0 {
		// Fallback: adaptive video only, will need audio merge
		for _, f := range info.Formats {
			if f.IsVideo && f.VCodec != "" {
				candidates = append(candidates, f)
			}
		}
	}

	if len(candidates) == 0 {
		return MediaFormat{}, errors.New("no video formats found")
	}

	// Sort by quality preference
	sort.Slice(candidates, func(i, j int) bool {
		return e.qualityRank(candidates[i].Quality) > e.qualityRank(candidates[j].Quality)
	})

	// Filter by quality preference
	if qualityPref != "" && qualityPref != "best" {
		var filtered []MediaFormat
		targetHeight := parseHeight(qualityPref)
		for _, f := range candidates {
			if f.Height <= targetHeight {
				filtered = append(filtered, f)
			}
		}
		if len(filtered) > 0 {
			candidates = filtered
		}
	}

	return candidates[0], nil
}

func (e *YouTubeExtractor) getBestAudio(info *MediaInfo) (MediaFormat, error) {
	var candidates []MediaFormat
	for _, f := range info.Formats {
		if f.IsAudio && f.ACodec != "" {
			candidates = append(candidates, f)
		}
	}
	if len(candidates) == 0 {
		return MediaFormat{}, errors.New("no audio formats found")
	}
	sort.Slice(candidates, func(i, j int) bool {
		return candidates[i].Bitrate > candidates[j].Bitrate
	})
	return candidates[0], nil
}

func (e *YouTubeExtractor) qualityRank(q string) int {
	q = strings.ToLower(q)
	switch {
	case strings.Contains(q, "4320") || strings.Contains(q, "8k"):
		return 80
	case strings.Contains(q, "2160") || strings.Contains(q, "4k"):
		return 70
	case strings.Contains(q, "1440") || strings.Contains(q, "2k"):
		return 60
	case strings.Contains(q, "1080"):
		return 50
	case strings.Contains(q, "720"):
		return 40
	case strings.Contains(q, "480"):
		return 30
	case strings.Contains(q, "360"):
		return 20
	case strings.Contains(q, "240"):
		return 10
	case strings.Contains(q, "144"):
		return 5
	case q == "audio_only":
		return 1
	default:
		return 0
	}
}

func parseHeight(q string) int {
	q = strings.ToLower(q)
	q = strings.TrimSuffix(q, "p")
	var h int
	fmt.Sscanf(q, "%d", &h)
	return h
}

func (e *YouTubeExtractor) Download(ctx context.Context, url string, format MediaFormat, progress ProgressFunc) (*DownloadResult, error) {
	downloader := NewHTTPDownloader("/tmp/media-downloader")

	// For progressive formats (video+audio in one), direct download
	if format.VCodec != "" && format.ACodec != "" {
		dest := downloader.GetTempFile(format.Ext)
		err := downloader.Download(ctx, format.URL, dest, progress)
		if err != nil {
			return nil, err
		}
		info, _ := os.Stat(dest)
		return &DownloadResult{
			FilePath:     dest,
			Format:       format,
			FileSize:     info.Size(),
			DownloadedAt: time.Now(),
		}, nil
	}

	// Adaptive: need to download video and audio separately and merge with ffmpeg
	// First, get the best audio format
	info, err := e.Extract(ctx, url)
	if err != nil {
		return nil, err
	}
	audioFormat, err := e.getBestAudio(info)
	if err != nil {
		return nil, err
	}

	return downloader.DownloadAdaptive(ctx, format.URL, audioFormat.URL, format, progress)
}